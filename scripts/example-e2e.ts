import { chromium } from 'playwright';
import { pathToFileURL } from 'node:url';
const out = process.argv[2];
const t0 = Date.now();
const b = await chromium.launch({ channel: 'chrome', headless: true, args: ['--window-size=1440,900'] });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
await ctx.addInitScript(() => { localStorage.setItem('span2:seenWelcome', 'true'); localStorage.setItem('span2:level', '"l7"'); });
const p = await ctx.newPage();
const errors: string[] = [];
p.on('pageerror', (e) => errors.push(e.message));
await p.goto(pathToFileURL(process.cwd() + '/Play Span.html').href);
await p.waitForSelector('#brief:not(.hidden) [data-ex]');
await p.evaluate(() => document.querySelector('#briefCard [data-ex]')!.scrollIntoView({ block: 'center' }));
await p.screenshot({ path: `${out}/e-brief.jpg`, quality: 55, type: 'jpeg' });
await p.click('#briefCard [data-ex]');
await p.waitForTimeout(600);
console.log('after load:', await p.textContent('#checkPill'), '|', await p.textContent('#cost'));
await p.screenshot({ path: `${out}/e-loaded.jpg`, quality: 55, type: 'jpeg' });
await p.click('#speedBtn'); await p.click('#speedBtn');
await p.click('#playBtn');
await p.waitForSelector('#modal:not(.hidden) .result', { timeout: 90000 });
await p.waitForTimeout(400);
console.log('result:', await p.textContent('#modalCard h2'), '|', await p.textContent('.diag-head b'));
console.log('stars saved:', await p.evaluate(() => localStorage.getItem('span2:progress')));
await p.screenshot({ path: `${out}/e-result.jpg`, quality: 55, type: 'jpeg' });
console.log('errors', errors, 'ms', Date.now() - t0);
await b.close();
