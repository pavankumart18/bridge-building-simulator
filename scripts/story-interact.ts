/** Drives the new interactive parts of the story (and the game's zoom bar) and screenshots them. */
import { chromium, type Page } from 'playwright';
import { pathToFileURL } from 'node:url';
const out = process.argv[2];
const t0 = Date.now();
const b = await chromium.launch({ channel: 'chrome', headless: true, args: ['--window-size=1440,900'] });
const errors: string[] = [];
const watch = (p: Page) => { p.on('pageerror', (e) => errors.push(e.message)); p.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); }); };
const to = (p: Page, step: string) => p.evaluate((s) => { document.documentElement.style.scrollBehavior = 'auto'; document.querySelector(`[data-step="${s}"]`)!.scrollIntoView({ block: 'center' }); }, step);

const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
watch(p);
await p.goto(pathToFileURL(process.cwd() + '/Bridge Story.html').href);
await p.waitForTimeout(800);
await p.click('#picker [data-k="bus"]');
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/i-hero-bus.jpg`, quality: 55, type: 'jpeg' });
await to(p, 'predict'); await p.waitForTimeout(700);
await p.click('[data-quiz="chord"] button[data-v="deck"]'); await p.waitForTimeout(500);
await p.screenshot({ path: `${out}/i-predict.jpg`, quality: 55, type: 'jpeg' });
await to(p, 'break'); await p.waitForTimeout(800);
await p.evaluate(() => { const l = document.querySelector<SVGElement>('#s3b line.removable.steel'); l!.dispatchEvent(new MouseEvent('click', { bubbles: true })); });
await p.waitForTimeout(300);
await p.click('#breakGo');
await p.waitForTimeout(7000);
await p.screenshot({ path: `${out}/i-break.jpg`, quality: 55, type: 'jpeg' });
console.log('break result:', await p.textContent('#breakOut'));
await to(p, 'rule'); await p.waitForTimeout(700);
await p.screenshot({ path: `${out}/i-fieldnote.jpg`, quality: 55, type: 'jpeg' });
await to(p, 'guess6'); await p.waitForTimeout(900);
await p.click('[data-quiz="margin"] button:nth-child(3)'); await p.waitForTimeout(400);
console.log('margin quiz:', await p.textContent('[data-quiz="margin"] .q-out'));
await p.evaluate(() => document.getElementById('challenge')!.scrollIntoView({ block: 'start' }));
await p.waitForTimeout(600);
await p.screenshot({ path: `${out}/i-challenge.jpg`, quality: 55, type: 'jpeg' });
await p.selectOption('[data-k="chord"]', '2'); await p.selectOption('[data-k="web"]', '2');
await p.evaluate(() => { const r = document.querySelector<HTMLInputElement>('[data-k="panels"]')!; r.value = '6'; r.dispatchEvent(new Event('input')); const d = document.querySelector<HTMLInputElement>('[data-k="depth"]')!; d.value = '2.5'; d.dispatchEvent(new Event('input')); });
await p.waitForTimeout(300);
console.log('challenge:', (await p.textContent('.ch-stars em')), (await p.textContent('.ch-facts'))?.replace(/\s+/g, ' '));
await p.click('#chTest'); await p.waitForTimeout(9000);
console.log('challenge test:', await p.textContent('#chTestOut'));
await p.screenshot({ path: `${out}/i-challenge-test.jpg`, quality: 55, type: 'jpeg' });
const [dl] = await Promise.all([p.waitForEvent('download', { timeout: 5000 }), p.click('#chShare')]);
console.log('share card:', dl.suggestedFilename());

const m = await (await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 })).newPage();
watch(m);
await m.goto(pathToFileURL(process.cwd() + '/Bridge Story.html').href);
await m.waitForTimeout(900);
await m.screenshot({ path: `${out}/m-hero.jpg`, quality: 50, type: 'jpeg' });
await to(m, 'colors'); await m.waitForTimeout(800);
await m.screenshot({ path: `${out}/m-c3.jpg`, quality: 50, type: 'jpeg' });
await to(m, 'push'); await m.waitForTimeout(800);
await m.screenshot({ path: `${out}/m-c4.jpg`, quality: 50, type: 'jpeg' });
console.log('mobile horizontal overflow:', await m.evaluate(() => document.documentElement.scrollWidth - innerWidth));

const g = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
watch(g);
await g.goto(pathToFileURL(process.cwd() + '/Play Span.html').href);
await g.click('[data-w="skip"]'); await g.click('#briefCard .btn.primary');
const z0 = await g.textContent('#zoomVal');
await g.click('#zoomIn'); await g.waitForTimeout(400); await g.click('#zoomIn'); await g.waitForTimeout(400);
const z1 = await g.textContent('#zoomVal');
await g.click('#zoomOut'); await g.waitForTimeout(400);
const z2 = await g.textContent('#zoomVal');
await g.screenshot({ path: `${out}/g-zoom.jpg`, quality: 55, type: 'jpeg' });
await g.click('#zoomFit'); await g.waitForTimeout(200);
console.log('game zoom:', z0, '→', z1, '→', z2, '→ fit', await g.textContent('#zoomVal'));
console.log('errors:', errors, 'ms', Date.now() - t0);
await b.close();
